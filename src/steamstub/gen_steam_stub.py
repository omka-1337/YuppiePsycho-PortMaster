#!/usr/bin/env python3
"""Generate the Steam stub C sources.

    gen_steam_stub.py steam_api OUT.c        -> libsteam_api stub
    gen_steam_stub.py encryptedappticket OUT.c

The symbol lists were collected with ypport.py from the P/Invoke tables of
Steamworks.NET 15.0.1 / 20.1.0 / 20.2.0 / 2024.8.0 and Facepunch.Steamworks
2.3.3. Hand-written entry points live in steam_stub_base.c; everything else
returns 0 (false / NULL / k_EResultNone-like values).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# Accessors that must hand out a (dummy) interface pointer in fake mode,
# otherwise Steamworks.NET's CSteamAPIContext.Init() bails out.
IFACE_RE = re.compile(r"^(SteamAPI_Steam(?!GameServer)[A-Za-z]+_v\d+|SteamAPI_ISteamClient_GetISteam\w+)$")


def main():
    which, out = sys.argv[1], sys.argv[2]
    lines = ["/* generated by gen_steam_stub.py - do not edit */",
             "#include <stdint.h>", "#include <stddef.h>"]
    if which == "steam_api":
        with open(os.path.join(HERE, "steam_stub_base.c")) as f:
            base = f.read()
        defined = set(re.findall(r"^YP_EXPORT[^(]*?\b(\w+)\(", base, re.M))
        lines.append(base)
        symbols = os.path.join(HERE, "steam_api_symbols.txt")
    elif which == "encryptedappticket":
        defined = set()
        lines.append('#define YP_EXPORT __attribute__((visibility("default")))')
        lines.append("#define YP_TRACE(n) do { } while (0)")
        symbols = os.path.join(HERE, "encryptedappticket_symbols.txt")
    else:
        raise SystemExit("unknown stub %r" % which)

    with open(symbols) as f:
        names = [l.strip() for l in f if l.strip() and not l.startswith("#")]
    count = 0
    for name in sorted(set(names)):
        if name in defined:
            continue
        if not re.match(r"^[A-Za-z_]\w*$", name):
            raise SystemExit("bad symbol %r" % name)
        if which == "steam_api" and IFACE_RE.match(name):
            lines.append('YP_EXPORT void *%s(void) { YP_TRACE("%s"); return yp_iface(); }' % (name, name))
        else:
            lines.append('YP_EXPORT uint64_t %s(void) { YP_TRACE("%s"); return 0; }' % (name, name))
        count += 1
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("%s: %d generated + %d hand-written entry points" % (out, count, len(defined)))


if __name__ == "__main__":
    main()
